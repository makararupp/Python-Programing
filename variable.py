# 1. Basic / Primitive Data Types
name = "Makara"         # str (String)
age = 23                # int (Integer)
salary = 500.50         # float (Float / Decimal)
active = True           # bool (Boolean)

# 2. Collection Data Types
skills = ["Python", "JavaScript", "HTML"]   # list (List)
coordinates = (10, 20)                      # tuple (Tuple)
person = {"name": "Makara", "age": 23}      # dict (Dictionary)
unique_numbers = {1, 2, 3, 3}               # set (Set)
bonus = None                                # NoneType

# 3. Check Data Types
print("name is:", type(name))
print("age is:", type(age))
print("salary is:", type(salary))
print("active is:", type(active))
print("skills is:", type(skills))
print("coordinates is:", type(coordinates))
print("person is:", type(person))
print("unique_numbers is:", type(unique_numbers))
print("bonus is:", type(bonus))
